-- Creating an Analytics View to connect with PowerBi
 CREATE OR REPLACE VIEW VW_TICKET_ANALYTICS AS
SELECT
    f.TICKET_ID,

    od.FULL_DATE AS OPEN_DATE,
    cd.FULL_DATE AS CLOSE_DATE,

    c.CATEGORY_NAME,
    a.AGENT_NAME,
    d.DEPARTMENT_NAME,
    p.PRIORITY_NAME,
    s.STATUS_NAME,
    i.IMPACT_NAME,

    f.RESOLUTION_HOURS,
    f.SLA_HOURS,
    f.USER_FEEDBACK_RATING,
    f.SLA_BREACHED

FROM FACT_TICKETS f

LEFT JOIN DIM_DATE od
    ON f.OPEN_DATE_KEY = od.DATE_KEY

LEFT JOIN DIM_DATE cd
    ON f.CLOSE_DATE_KEY = cd.DATE_KEY

LEFT JOIN DIM_CATEGORY c
    ON f.CATEGORY_KEY = c.CATEGORY_KEY

LEFT JOIN DIM_AGENT a
    ON f.AGENT_KEY = a.AGENT_KEY

LEFT JOIN DIM_DEPARTMENT d
    ON f.DEPARTMENT_KEY = d.DEPARTMENT_KEY

LEFT JOIN DIM_PRIORITY p
    ON f.PRIORITY_KEY = p.PRIORITY_KEY

LEFT JOIN DIM_STATUS s
    ON f.STATUS_KEY = s.STATUS_KEY

LEFT JOIN DIM_IMPACT i
    ON f.IMPACT_KEY = i.IMPACT_KEY;
    
SELECT *
FROM VW_TICKET_ANALYTICS
FETCH FIRST 20 ROWS ONLY;    
    
    
