--Check for NULLs in Critical Fields
SELECT *
FROM FACT_TICKETS
WHERE TICKET_ID IS NULL
   OR PRIORITY_KEY IS NULL
   OR STATUS_KEY IS NULL;
   
--Duplicate Ticket Check
SELECT TICKET_ID, COUNT(*) AS DUPLICATE_COUNT
FROM FACT_TICKETS
GROUP BY TICKET_ID
HAVING COUNT(*) > 1;

--Missing Agent Assignment
SELECT *
FROM FACT_TICKETS
WHERE AGENT_KEY IS NULL;














